import { useGLTF } from '@react-three/drei';
import { useFrame, useThree } from '@react-three/fiber';
import gsap from 'gsap';
import { useEffect, useLayoutEffect, useMemo, useRef } from 'react';

// The top of the model, its ceiling plate. The pivot sits exactly here so the
// plate stays fixed and only the cord and shade swing below it.
const PLATE_Y = 3;
const SWING_ANGLE = (9 * Math.PI) / 180;

// The model's cord hangs the shade too low for this room, so it's shortened at
// load: the shade moves up by CORD_CUT and the cord between it and the plate is
// squeezed to fit. Heights are the model's own.
const SHADE_TOP_Y = 2.32;
const PLATE_BOTTOM_Y = 2.92;
const CORD_CUT = 0.42;
const LIFTED_SHADE_TOP_Y = SHADE_TOP_Y + CORD_CUT;

function shortenCord(source)
{
  const geometry = source.clone();
  const position = geometry.attributes.position;
  const squeeze = (PLATE_BOTTOM_Y - LIFTED_SHADE_TOP_Y) / (PLATE_BOTTOM_Y - SHADE_TOP_Y);

  for (let i = 0; i < position.count; i++) {
    const y = position.getY(i);
    if (y <= SHADE_TOP_Y) position.setY(i, y + CORD_CUT);
    else if (y < PLATE_BOTTOM_Y) position.setY(i, PLATE_BOTTOM_Y - (PLATE_BOTTOM_Y - y) * squeeze);
  }

  geometry.computeBoundingBox();
  geometry.computeBoundingSphere();
  return geometry;
}

// Where the lamp waits by day, well above the frame.
const RAISED_Y = 14;

const SPOT_INTENSITY = 2.6;
const AMBIENT_INTENSITY = 0.3;

// `on` drops the lamp in and lights it. Everything stays mounted while it's off:
// adding or removing a light makes three recompile every material, which would
// land as a hitch at the exact moment of the drop. So "off" is intensity 0 and a
// hidden mesh, not an unmounted light.
export default function Model({ on, ...props }) {
  const { nodes, materials } = useGLTF('/lamplight-transformed.glb')
  const invalidate = useThree((state) => state.invalidate)
  const lampGeometry = useMemo(() => shortenCord(nodes.Bulb.geometry), [nodes])
  const dropRef = useRef();
  const pivotRef = useRef();
  const lampRef = useRef();
  const cordRef = useRef();
  const lightRef = useRef();
  const ambientRef = useRef();

  const setShown = (shown) => {
    materials.re_lamp_02.visible = shown
    cordRef.current.visible = shown
  }

  const applyFinalState = (lit) => {
    setShown(lit)
    dropRef.current.position.y = lit ? 0 : RAISED_Y
    pivotRef.current.rotation.z = 0
    lightRef.current.intensity = lit ? SPOT_INTENSITY : 0
    ambientRef.current.intensity = lit ? AMBIENT_INTENSITY : 0
    materials.re_lamp_02.emissiveIntensity = lit ? 1 : 0
  }

  useLayoutEffect(() => applyFinalState(false), [])

  const hasMounted = useRef(false)
  useEffect(() => {
    if (!hasMounted.current) {
      hasMounted.current = true
      return
    }

    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
      applyFinalState(on)
      invalidate()
      return
    }

    // The invalidate keeps this running while the Canvas is on demand rendering
    // with the camera parked at the monitor.
    const timeline = gsap.timeline({ onUpdate: invalidate })
    const light = lightRef.current
    const bulb = materials.re_lamp_02

    if (on) {
      setShown(true)
      timeline
        .fromTo(dropRef.current.position, { y: RAISED_Y }, { y: 0, duration: 0.55, ease: 'power2.in' }, 0.5)
        .fromTo(pivotRef.current.rotation, { z: SWING_ANGLE }, { z: 0, duration: 5, ease: 'elastic.out(1, 0.32)' }, 1.05)
        // The bulb catches on the second try.
        .set(light, { intensity: SPOT_INTENSITY * 0.6 }, 1.45)
        .set(bulb, { emissiveIntensity: 0.6 }, 1.45)
        .set(light, { intensity: 0 }, 1.52)
        .set(bulb, { emissiveIntensity: 0 }, 1.52)
        .to(light, { intensity: SPOT_INTENSITY, duration: 0.25 }, 1.64)
        .to(bulb, { emissiveIntensity: 1, duration: 0.25 }, 1.64)
        .to(ambientRef.current, { intensity: AMBIENT_INTENSITY, duration: 0.25 }, 1.64)
    } else {
      timeline
        .to(light, { intensity: 0, duration: 0.15 }, 0)
        .to(bulb, { emissiveIntensity: 0, duration: 0.15 }, 0)
        .to(ambientRef.current, { intensity: 0, duration: 0.15 }, 0)
        .to(dropRef.current.position, { y: RAISED_Y, duration: 0.7, ease: 'power2.in' }, 0.2)
        .call(() => setShown(false))
    }

    return () => timeline.kill()
  }, [on]);

  useFrame(() => {
    if (lightRef.current && lampRef.current) {
      lightRef.current.target = lampRef.current;
    }
  })

  return (
    <group {...props} dispose={null}>
      <group ref={dropRef}>
        {/* Pivot Group: the fixed point, at the ceiling plate */}
        <group ref={pivotRef} position={[0, 0.09 + PLATE_Y, 0]}>
          {/* Lamp Mesh: hangs below the pivot */}
          <mesh
            ref={lampRef}
            geometry={lampGeometry}
            material={materials.re_lamp_02}
            position={[0, -PLATE_Y, 0]}
          >
            <mesh ref={cordRef} position={[0, (LIFTED_SHADE_TOP_Y + PLATE_Y) / 2, 0]}>
              <cylinderGeometry args={[0.014, 0.014, PLATE_Y - LIFTED_SHADE_TOP_Y, 6]} />
              <meshBasicMaterial color="#14110e" />
            </mesh>
            <ambientLight ref={ambientRef} color="#ffc98a" />
            <spotLight
              position={[0, 2 + CORD_CUT, 0]}
              target={lampRef.current}
              color={"#FFB454"}
              ref={lightRef} angle={0.95} penumbra={0.8} decay={0} />
          </mesh>
        </group>
      </group>
    </group>
  )
}

